var fileTime = time.Unix(1_700_000_000, 0)

func TestJobWatcherSaysWhenPrintsStartAndEnd(t *testing.T) {
	type step struct{ state, file, want string }
	cases := map[string][]step{
		"a print, start to finish": {{"standby", "", ""}, {"printing", "a.gcode", "printing"}, {"paused", "a.gcode", ""}, {"printing", "a.gcode", ""}, {"complete", "a.gcode", "complete"}, {"standby", "a.gcode", ""}},
		"cancelled, failed":        {{"standby", "", ""}, {"printing", "a.gcode", "printing"}, {"cancelled", "a.gcode", "cancelled"}, {"printing", "a.gcode", "printing"}, {"error", "a.gcode", "error"}},
		"file reset mid-print":     {{"printing", "a.gcode", "printing"}, {"standby", "", "cancelled"}},
		"another file at once":     {{"printing", "a.gcode", "printing"}, {"printing", "b.gcode", "printing"}},
		// A watch that begins mid-print says so; one that begins after an end passes the end on, marked late.
		"watch begins after an end": {{"complete", "a.gcode", "complete"}, {"complete", "a.gcode", ""}, {"standby", "", ""}},
		"nothing printed":           {{"standby", "", ""}, {"standby", "", ""}, {"complete", "a.gcode", ""}},
	}
	for name, steps := range cases {
		j := &jobWatcher{}
		for i, s := range steps {
			if got := j.update(s.state, s.file); got != s.want {
				t.Errorf("%s, step %d (%s %s): got %q, want %q", name, i, s.state, s.file, got, s.want)
			}
		}
	}
	j := &jobWatcher{}
	if j.update("complete", "a.gcode"); !j.late {
		t.Error("an end already there when the watch began should be late")
	}
	j.update("printing", "a.gcode")
	if j.update("complete", "a.gcode"); j.late {
		t.Error("an end seen happening isn't late")
	}
	if j.update("standby", ""); j.file != "" {
		t.Error("file should follow the printer")
	}
}

func TestPrintTagIn(t *testing.T) {
	head := "; HEADER_BLOCK_START\n; generated by OrcaSlicer\n; HEADER_BLOCK_END\n; cloud_slicer_print = b5c1-x_9/3/0123abcd0123abcd  \r\nG28\n"
	if got := printTagIn([]byte(head)); got != "; cloud_slicer_print = b5c1-x_9/3/0123abcd0123abcd" {
		t.Fatalf("got %q", got)
	}
	if printTagIn([]byte("G28\n; cloud_slicer_print_x = 1\n")) != "" {
		t.Fatal("no tag there")
	}
	// Cut at the end of what was read: whatever is there, the site checks it.
	if printTagIn([]byte("G28\n"+strings.Repeat("x", 300))) != "" {
		t.Fatal("no tag in a long line")
	}
}

func TestFileHeadReadsOnlyTheStartOfAMoonrakerFile(t *testing.T) {
	body := strings.Repeat("; line of G-code\n", 4000)
	var gotRange, gotKey, gotPath string
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		gotRange, gotKey, gotPath = r.Header.Get("Range"), r.Header.Get("X-Api-Key"), r.URL.EscapedPath()
		// Like Moonraker: the part asked for.
		http.ServeContent(w, r, "x.gcode", fileTime, strings.NewReader(body))
	}))
	defer srv.Close()
	head, err := fileHead(context.Background(), Printer{ID: "u1", URL: srv.URL, APIKey: "k"}, "sub dir/Benchy plate 1.gcode")
	if err != nil {
		t.Fatal(err)
	}
	if len(head) != headBytes || gotRange != "bytes=0-16383" || gotKey != "k" || gotPath != "/server/files/gcodes/sub%20dir/Benchy%20plate%201.gcode" {
		t.Fatalf("read %d bytes, range %q, key %q, path %q", len(head), gotRange, gotKey, gotPath)
	}
	// A server that ignores Range is cut off after the start.
	plain := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) { _, _ = w.Write([]byte(body)) }))
	defer plain.Close()
	if head, err := fileHead(context.Background(), Printer{ID: "u1", URL: plain.URL}, "a.gcode"); err != nil || len(head) != headBytes {
		t.Fatalf("read %d bytes: %v", len(head), err)
	}
	missing := httptest.NewServer(http.NotFoundHandler())
	defer missing.Close()
	if _, err := fileHead(context.Background(), Printer{ID: "u1", URL: missing.URL}, "a.gcode"); err == nil {
		t.Fatal("a missing file should fail")
	}
}

func TestOctoPrintHead(t *testing.T) {
	var gotPath, gotKey string
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		gotPath, gotKey = r.URL.EscapedPath(), r.Header.Get("X-Api-Key")
		http.ServeContent(w, r, "x.gcode", fileTime, strings.NewReader("; cloud_slicer_print = p/1/0123abcd\nG28\n"))
	}))
	defer srv.Close()
	head, err := newOctoPrint(srv.URL, "key").head(context.Background(), "parts/a b.gcode", headBytes)
	if err != nil || printTagIn(head) != "; cloud_slicer_print = p/1/0123abcd" || gotPath != "/downloads/files/local/parts/a%20b.gcode" || gotKey != "key" {
		t.Fatalf("head %q, path %q, key %q: %v", head, gotPath, gotKey, err)
	}
}

func TestStandInAsksLessOftenForTheQuietWatchOnly(t *testing.T) {
	s := &standIn{every: pollEvery, clients: map[*standInClient]bool{}}
	quiet, browser := &standInClient{quiet: true}, &standInClient{}
	s.clients[quiet] = true
	if s.interval() != quietEvery {
		t.Fatalf("quiet watch alone: %v", s.interval())
	}
	s.clients[browser] = true
	if s.interval() != pollEvery {
		t.Fatalf("with a browser: %v", s.interval())
	}
}
